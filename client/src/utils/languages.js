/**
 * Get language configuration by code
 */
export function getLanguageConfig(code = 'ta') {
  return (
    SUPPORTED_LANGUAGES.find((lang) => lang.code === code) ||
    SUPPORTED_LANGUAGES[0]
  )
}

/**
 * Get question string for a field in the selected language
 */
export function getFieldQuestionInLanguage(field, langCode = 'ta') {
  if (!field) return ''
  const translations = FIELD_QUESTION_TRANSLATIONS[field.id]
  if (translations && translations[langCode]) {
    return translations[langCode]
  }
  return (
    field.question?.[langCode] ||
    field.question?.ta ||
    field.question?.en ||
    field.labels?.[langCode] ||
    field.labels?.ta ||
    field.labels?.en ||
    ''
  )
}

